defmodule Cadence.ServerWeb.AuthController do
  @moduledoc """
  OAuth callback controller generated by AshAuthentication.Phoenix.
  """

  use Cadence.ServerWeb, :controller
  use AshAuthentication.Phoenix.Controller

  def success(conn, _activity, user, _token) do
    conn
    |> store_in_session(user)
    |> assign(:current_user, user)
    |> redirect(to: "/auth/tokens/new")
  end

  def failure(conn, _activity, _reason) do
    conn
    |> put_resp_content_type("text/html")
    |> send_resp(401, "Authentication failed")
  end

  def sign_out(conn, _params) do
    conn
    |> clear_session(:cadence_server)
    |> redirect(to: "/")
  end
end
