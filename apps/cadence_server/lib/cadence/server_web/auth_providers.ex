defmodule Cadence.ServerWeb.AuthProviders do
  @moduledoc """
  The OAuth providers that are actually configured for this deployment.

  An unconfigured provider is hidden from the sign-in page instead of rendering
  a button that can only fail.
  """

  @providers [:github, :google]

  @doc "Provider atoms with a client id configured."
  @spec configured() :: [atom()]
  def configured do
    oauth = Application.get_env(:cadence_server, :oauth, [])

    Enum.filter(@providers, fn provider ->
      case Keyword.get(oauth, provider, []) do
        config when is_list(config) -> present?(Keyword.get(config, :client_id))
        _other -> false
      end
    end)
  end

  @doc "Display label for a provider."
  @spec label(atom()) :: String.t()
  def label(:github), do: "GitHub"
  def label(:google), do: "Google"
  def label(provider), do: provider |> to_string() |> String.capitalize()

  @doc "Request-phase path generated by `auth_routes/3`."
  @spec path(atom()) :: String.t()
  def path(provider), do: "/auth/user/#{provider}"

  defp present?(value), do: is_binary(value) and String.trim(value) != ""
end
