defmodule Cadence.Daemon.CommitQueue do
  @moduledoc """
  Serializes commits for a single project.

  One `CommitQueue` GenServer runs per project (supervised by
  `Cadence.Daemon.ProjectRegistry`). It snapshots the working tree into the
  project's `GitStore`, writes a commit, and records the resulting `Node` in
  SQLite.

  The Git object store lives *outside* the working tree so `build_tree/2` never
  recurses into it.

  Commit messages may be supplied explicitly or generated by the LLM agent
  (`:auto`). Explicit messages are used as-is; `:auto` commits immediately with a
  placeholder and hands the node to `Cadence.Daemon.MessageQueue`, which fills
  the real message in the background (spec §5.3, §5.5). The commit path never
  blocks on the LLM.
  """

  use GenServer

  alias Cadence.Daemon.{Dirs, Env, MessageQueue, Repo, Session}
  alias Cadence.Shared.{GitStore, Node}

  @default_message "session commit"
  @default_author %{name: "cadence", email: "cadence@local"}

  defstruct [:project_id, :work_dir, :git, :author, :head]

  @type t :: %__MODULE__{head: Node.t() | nil}

  def start_link(opts) do
    {name, opts} = Keyword.pop(opts, :name)
    GenServer.start_link(__MODULE__, opts, name: name)
  end

  @doc """
  Commits the current working tree, returning `{:ok, node}`.

  `message` may be an explicit string or `:auto` (default) to generate one via
  the LLM agent.
  """
  def commit(queue, message \\ :auto) do
    GenServer.call(queue, {:commit, message})
  end

  @doc """
  Spawns a `sandbox` child node from the current session-pointer node.

  Reuses the current node's tree (no working-tree change), records a node with
  `flags: [:sandbox]` and `parents: [current.id]`, then advances the session
  pointer and adds the parent to the user's active heads (spec §6.4).
  """
  def spawn(queue, name \\ "spawn") do
    GenServer.call(queue, {:spawn, name})
  end

  @impl true
  def init(opts) do
    project_id = Keyword.fetch!(opts, :project_id)
    work_dir = Path.expand(Keyword.fetch!(opts, :work_dir))
    git_dir = Path.expand(Keyword.fetch!(opts, :git_dir))
    author = Keyword.get(opts, :author, @default_author)

    Dirs.ensure!(git_dir)
    File.mkdir_p!(work_dir)

    {:ok,
     %__MODULE__{
       project_id: project_id,
       work_dir: work_dir,
       git: GitStore.init(git_dir, bare: true),
       author: author,
       head: latest_node(project_id)
     }}
  end

  @impl true
  def handle_call({:commit, message}, _from, state) do
    {:ok, node} = do_commit(state, message)
    {:reply, {:ok, node}, %{state | head: node}}
  end

  @impl true
  def handle_call({:spawn, name}, _from, state) do
    case Session.current_node(state.project_id) do
      nil ->
        {:reply, {:error, :no_current_node}, state}

      current ->
        {:ok, node} = do_spawn(state, current, name)
        {:reply, {:ok, node}, %{state | head: node}}
    end
  end

  defp do_commit(state, message) do
    tree = GitStore.build_tree(state.git, state.work_dir, ignore: Env.ignore_names())

    {git_parents, node_parents} =
      case base_node(state) do
        nil -> {[], []}
        %{git_commit_sha: sha, id: id} -> {[sha], [id]}
      end

    {message, flags, metadata} = message_attrs(message)

    sha = GitStore.write_commit(state.git, tree, git_parents, state.author, message)

    attrs = %{
      project_id: state.project_id,
      git_commit_sha: sha,
      parents: node_parents,
      flags: flags,
      message: message,
      session_metadata: metadata,
      created_by: Env.local_user_id(),
      created_at: DateTime.utc_now(),
      docs_state: :pending
    }

    {:ok, node} = attrs |> Node.changeset() |> Repo.insert()
    Session.commit_after(state.project_id, node)

    if metadata["message_pending"] == true do
      MessageQueue.enqueue(node.project_id, node.id)
    end

    {:ok, node}
  end

  defp do_spawn(state, current, name) do
    tree = GitStore.read_commit(state.git, current.git_commit_sha).tree
    sha = GitStore.write_commit(state.git, tree, [current.git_commit_sha], state.author, name)

    attrs = %{
      project_id: state.project_id,
      git_commit_sha: sha,
      parents: [current.id],
      flags: [:sandbox],
      message: name,
      session_metadata: %{},
      created_by: Env.local_user_id(),
      created_at: DateTime.utc_now(),
      docs_state: :current
    }

    {:ok, node} = attrs |> Node.changeset() |> Repo.insert()
    Session.spawn_after(state.project_id, current, node)
    {:ok, node}
  end

  defp message_attrs(message) when is_binary(message) do
    {message, [:"in-progress"], %{}}
  end

  # Auto messages are generated off the commit path: write a placeholder now and
  # let `MessageQueue` fill the real message in the background. This keeps the
  # watcher non-blocking (spec §5.3, §5.5).
  defp message_attrs(:auto) do
    {@default_message, [:"in-progress"], %{"message_pending" => true}}
  end

  # The parent for a normal commit is the node the local user is currently
  # editing from (spec §3.2). It falls back to the last committed node only
  # before any pointer exists (the first commit).
  defp base_node(state) do
    Session.current_node(state.project_id) || state.head
  end

  defp latest_node(project_id) do
    import Ecto.Query

    Node
    |> where([n], n.project_id == ^project_id)
    |> order_by([n], desc: n.created_at, desc: n.id)
    |> limit(1)
    |> Repo.one()
  end
end
