defmodule Cadence.Daemon.CommitQueue do
  @moduledoc """
  Serializes commits for a single project.

  One `CommitQueue` GenServer runs per project (supervised by
  `Cadence.Daemon.ProjectRegistry`). It snapshots the working tree into the
  project's `GitStore`, writes a commit, and records the resulting `Node` in
  SQLite.

  The Git object store lives *outside* the working tree so `build_tree/2` never
  recurses into it.

  Commit messages may be supplied explicitly or generated by the LLM agent
  (`:auto`). Explicit messages are used as-is; `:auto` commits immediately with a
  placeholder and hands the node to `Cadence.Daemon.MessageQueue`, which fills
  the real message in the background (spec §5.3, §5.5). The commit path never
  blocks on the LLM.
  """

  use GenServer

  alias Cadence.Daemon.{
    Dirs,
    DocQueue,
    Docs.SchemaSource,
    Env,
    MessageQueue,
    Nodes,
    Repo,
    Session,
    SyncLedger
  }

  alias Cadence.Shared.{GitStore, Node}
  alias Cadence.Shared.Docs.{Schema, Trigger}

  @default_message "session commit"

  defstruct [:project_id, :work_dir, :git, :author, :head]

  @type t :: %__MODULE__{head: Node.t() | nil}

  def start_link(opts) do
    {name, opts} = Keyword.pop(opts, :name)
    GenServer.start_link(__MODULE__, opts, name: name)
  end

  @doc """
  Commits the current working tree, returning `{:ok, node}`.

  `message` may be an explicit string or `:auto` (default) to generate one via
  the LLM agent.

  Options:

    * `:skip_unchanged` — return the base node without writing a commit when the
      working tree equals the base node's tree. The watcher uses this so an
      automated write (or a duplicate file event) cannot create an empty node.
    * `:flags` — node flags for the commit. Defaults to `[:in-progress]`; the
      hub's initial snapshot passes `[:imported]`.
    * `:timeout` — GenServer call timeout (default 5 s). The hub's first
      snapshot of a large existing tree uses a longer bound.
  """
  @spec commit(GenServer.server(), String.t() | :auto, keyword()) ::
          {:ok, Node.t()} | {:error, term()}
  def commit(queue, message \\ :auto, opts \\ []) do
    GenServer.call(queue, {:commit, message, opts}, Keyword.get(opts, :timeout, 5_000))
  end

  @doc """
  Spawns a `sandbox` child node from the current session-pointer node.

  Reuses the current node's tree (no working-tree change), records a node with
  `flags: [:sandbox]` and `parents: [current.id]`, then advances the session
  pointer and adds the parent to the user's active heads (spec §6.4).
  """
  def spawn(queue, name \\ "spawn") do
    GenServer.call(queue, {:spawn, name})
  end

  @impl true
  def init(opts) do
    project_id = Keyword.fetch!(opts, :project_id)
    work_dir = Path.expand(Keyword.fetch!(opts, :work_dir))
    git_dir = Path.expand(Keyword.fetch!(opts, :git_dir))
    author = Keyword.get(opts, :author, Env.git_author())

    Dirs.ensure!(git_dir)
    File.mkdir_p!(work_dir)

    {:ok,
     %__MODULE__{
       project_id: project_id,
       work_dir: work_dir,
       git: GitStore.init(git_dir, bare: true),
       author: author,
       head: Nodes.latest(project_id)
     }}
  end

  @impl true
  def handle_call({:commit, message, opts}, _from, state) do
    {:ok, node} = do_commit(state, message, opts)
    {:reply, {:ok, node}, %{state | head: node}}
  end

  @impl true
  def handle_call({:spawn, name}, _from, state) do
    case Session.current_node(state.project_id) do
      nil ->
        {:reply, {:error, :no_current_node}, state}

      current ->
        {:ok, node} = do_spawn(state, current, name)
        {:reply, {:ok, node}, %{state | head: node}}
    end
  end

  defp do_commit(state, message, opts) do
    tree = GitStore.build_tree(state.git, state.work_dir, ignore: Env.ignore_names())

    base = base_node(state)

    {git_parents, node_parents, old_tree} =
      case base do
        nil ->
          {[], [], nil}

        %{git_commit_sha: sha, id: id} ->
          {[sha], [id], read_tree(state.git, sha)}
      end

    if Keyword.get(opts, :skip_unchanged, false) and old_tree == tree do
      {:ok, base}
    else
      do_write_commit(state, message, opts, tree, git_parents, node_parents, old_tree)
    end
  end

  defp do_write_commit(state, message, opts, tree, git_parents, node_parents, old_tree) do
    {message, flags, metadata} = message_attrs(message, opts)

    sha = GitStore.write_commit(state.git, tree, git_parents, state.author, message)
    changes = diff_changes(state.git, old_tree, tree)

    {docs_state, docs_metadata, docs_queued?} =
      if :imported in flags do
        {:skipped, %{}, false}
      else
        docs_plan(state, changes, sha)
      end

    metadata = Map.merge(metadata, docs_metadata)

    attrs = %{
      project_id: state.project_id,
      git_commit_sha: sha,
      parents: node_parents,
      flags: flags,
      message: message,
      session_metadata: metadata,
      created_by: Env.local_user_id(),
      created_at: DateTime.utc_now(),
      docs_state: docs_state
    }

    {:ok, node} =
      Repo.transaction(fn ->
        {:ok, node} = attrs |> Node.changeset() |> Repo.insert()
        {:ok, _membership} = Session.commit_after(state.project_id, node)
        # Persist the sync row with the node: a lost notification cast must
        # never leave a parent without a row (spec §9.5, parents-first).
        SyncLedger.insert_pending!(node)
        node
      end)

    if metadata["message_pending"] == true do
      MessageQueue.enqueue(node.project_id, node.id)
    end

    # Every node gets a sync row immediately; while a doc job is outstanding
    # the ledger holds it out of selection but keeps its children behind it
    # (spec §9.5, parents-first). `DocQueue` re-enqueues on terminal so the
    # worker wakes even if the initial pass already ran.
    SyncLedger.enqueue(state.project_id, node.id)

    if docs_queued? do
      DocQueue.enqueue(node.project_id, node.id)
    end

    {:ok, node}
  end

  defp do_spawn(state, current, name) do
    tree = GitStore.read_commit(state.git, current.git_commit_sha).tree
    sha = GitStore.write_commit(state.git, tree, [current.git_commit_sha], state.author, name)

    attrs = %{
      project_id: state.project_id,
      git_commit_sha: sha,
      parents: [current.id],
      flags: [:sandbox],
      message: name,
      session_metadata: %{},
      created_by: Env.local_user_id(),
      created_at: DateTime.utc_now(),
      docs_state: :current
    }

    {:ok, node} =
      Repo.transaction(fn ->
        {:ok, node} = attrs |> Node.changeset() |> Repo.insert()
        {:ok, _membership} = Session.spawn_after(state.project_id, current, node)
        SyncLedger.insert_pending!(node)
        node
      end)

    SyncLedger.enqueue(state.project_id, node.id)
    {:ok, node}
  end

  defp message_attrs(message, opts) when is_binary(message) do
    {message, Keyword.get(opts, :flags, [:"in-progress"]), %{}}
  end

  # Auto messages are generated off the commit path: write a placeholder now and
  # let `MessageQueue` fill the real message in the background. This keeps the
  # watcher non-blocking (spec §5.3, §5.5).
  defp message_attrs(:auto, opts) do
    {@default_message, Keyword.get(opts, :flags, [:"in-progress"]), %{"message_pending" => true}}
  end

  # Evaluates doc automation for a commit (spec §9.2). The schema file is the
  # source of truth; the cached `Project.docs_schema` is refreshed only when the
  # file itself changed this commit.
  defp docs_plan(state, changes, sha) do
    if Env.docs_enabled?() do
      case load_schema(state, changes) do
        {:ok, schema} ->
          case Trigger.reasons(schema, changes) do
            {:run, reasons} ->
              docs = %{
                "state" => "pending",
                "code_commit_sha" => sha,
                "reasons" => Enum.map(reasons, &Atom.to_string/1)
              }

              {:pending, %{"code_commit_sha" => sha, "docs" => docs}, true}

            :skip ->
              {:skipped, %{}, false}
          end

        :no_schema ->
          {:skipped, %{}, false}

        {:error, reason} ->
          {:skipped, %{"docs" => %{"state" => "skipped", "error" => Atom.to_string(reason)}},
           false}
      end
    else
      {:skipped, %{}, false}
    end
  end

  defp load_schema(state, changes) do
    if Enum.any?(changes, &(&1.path == Schema.schema_file())) do
      SchemaSource.refresh(state.project_id, state.work_dir)
    else
      SchemaSource.load(state.work_dir)
    end
  end

  defp read_tree(git, sha) do
    case GitStore.read_commit(git, sha) do
      nil -> nil
      commit -> commit.tree
    end
  end

  # A commit must succeed even if the base commit's tree object is missing
  # (corrupt local store). Degrade to "no visible changes" so docs are skipped
  # instead of crashing the commit queue.
  defp diff_changes(git, old_tree, tree) do
    GitStore.diff_trees(git, old_tree, tree)
  rescue
    ArgumentError -> []
  end

  # The parent for a normal commit is the node the local user is currently
  # editing from (spec §3.2). With no explicit pointer yet, the session anchors
  # on the user's most-recent node (or the preview node) — never another user's
  # tip (spec §6.3). `state.head` is a last resort for an empty project.
  defp base_node(state) do
    Session.anchor_node(state.project_id) || state.head
  end
end
