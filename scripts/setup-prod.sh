#!/usr/bin/env bash
# Generate a production .env and (optionally) start the reference stack.
#
#   ./scripts/setup-prod.sh cadence.example.com you@example.com --up
#   ./scripts/setup-prod.sh cadence.lan admin@cadence.lan --tls internal --up
#   ./scripts/setup-prod.sh cadence.example.com you@example.com --tls external
#
# The script never overwrites an existing .env unless --force is passed.

set -euo pipefail

ROOT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
ENV_FILE="$ROOT_DIR/.env"

usage() {
  cat <<'EOF'
Usage: scripts/setup-prod.sh <hostname> [admin-email] [options]

Options:
  --tls auto|internal|external  TLS mode (default: auto)
                                  auto     — bundled Caddy + Let's Encrypt
                                  internal — bundled Caddy + private local CA
                                  external — no Caddy; use your own proxy
  --no-actions                  Set CAD_ACTIONS_ENABLED=false
  --up                          Start the stack after writing .env
  --force                       Overwrite an existing .env
  -h, --help                    Show this help
EOF
}

HOST=""
EMAIL=""
TLS_MODE="auto"
ACTIONS="true"
UP="false"
FORCE="false"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --tls)
      if [[ $# -lt 2 ]]; then
        echo "--tls requires auto, internal, or external" >&2
        exit 2
      fi
      TLS_MODE="$2"
      shift 2
      ;;
    --tls=*)
      TLS_MODE="${1#--tls=}"
      shift
      ;;
    --no-actions)
      ACTIONS="false"
      shift
      ;;
    --up)
      UP="true"
      shift
      ;;
    --force)
      FORCE="true"
      shift
      ;;
    -h | --help)
      usage
      exit 0
      ;;
    -*)
      echo "Unknown option: $1" >&2
      usage >&2
      exit 2
      ;;
    *)
      if [[ -z "$HOST" ]]; then
        HOST="$1"
      elif [[ -z "$EMAIL" ]]; then
        EMAIL="$1"
      else
        echo "Unexpected argument: $1" >&2
        usage >&2
        exit 2
      fi
      shift
      ;;
  esac
done

case "$TLS_MODE" in
  auto | internal | external) ;;
  *)
    echo "Invalid --tls value: $TLS_MODE (expected auto, internal, or external)" >&2
    exit 2
    ;;
esac

HOST="${HOST#http://}"
HOST="${HOST#https://}"
HOST="${HOST%%/*}"

if [[ -z "$HOST" ]]; then
  usage >&2
  exit 2
fi

if [[ -z "$EMAIL" ]]; then
  EMAIL="admin@$HOST"
fi

if [[ -f "$ENV_FILE" && "$FORCE" != "true" ]]; then
  echo "$ENV_FILE already exists; pass --force to replace it." >&2
  exit 1
fi

command -v openssl >/dev/null 2>&1 || {
  echo "openssl is required to generate secrets." >&2
  exit 1
}

SECRET_KEY_BASE="$(openssl rand -hex 48)"
DB_PASSWORD="$(openssl rand -hex 24)"
ADMIN_PASSWORD="$(openssl rand -hex 16)"
ADMIN_NAME="${CAD_ADMIN_NAME:-Cadence Admin}"

umask 077
cat >"$ENV_FILE" <<EOF
# Generated by scripts/setup-prod.sh.
# Keep this file private (chmod 600) and never commit it.

CAD_PHX_HOST=$HOST
CAD_PUBLIC_URL=https://$HOST
CAD_SECRET_KEY_BASE=$SECRET_KEY_BASE
CAD_HTTP_PORT=4000
# The bundled Caddy profile needs 127.0.0.1; an external proxy on another
# host needs 0.0.0.0 instead.
CAD_HTTP_BIND=127.0.0.1

CAD_DB_USER=cadence
CAD_DB_PASS=$DB_PASSWORD
CAD_DB_NAME=cadence
CAD_DB_POOL_SIZE=10

CAD_ADMIN_EMAIL=$EMAIL
CAD_ADMIN_NAME=$ADMIN_NAME
CAD_ADMIN_PASSWORD=$ADMIN_PASSWORD

CAD_TLS_MODE=$TLS_MODE
CAD_ACTIONS_ENABLED=$ACTIONS
EOF
chmod 600 "$ENV_FILE"

echo "Wrote $ENV_FILE (chmod 600)."
echo
echo "Admin email:    $EMAIL"
echo "Admin password: $ADMIN_PASSWORD"
echo
echo "Sign in at https://$HOST/sign-in and enroll TOTP on the first login."
echo "After the first sign-in, remove CAD_ADMIN_PASSWORD from $ENV_FILE."
echo

case "$TLS_MODE" in
  auto)
    echo "TLS: bundled Caddy obtains a certificate for $HOST (ports 80/443 must be open)."
    ;;
  internal)
    echo "TLS: bundled Caddy uses its local CA. Trust the root certificate on your clients:"
    echo "  docker compose -f docker-compose.prod.yml exec caddy cat /data/caddy/pki/authorities/local/root.crt > cadence-ca.crt"
    ;;
  external)
    echo "TLS: no Caddy. Point your reverse proxy at http://127.0.0.1:4000."
    ;;
esac

if [[ "$UP" == "true" ]]; then
  compose=(docker compose -f docker-compose.prod.yml)
  if [[ "$TLS_MODE" != "external" ]]; then
    compose+=(--profile tls)
  fi
  "${compose[@]}" up -d --build
  echo
  echo "Stack started. Follow logs with:"
  echo "  ${compose[*]} logs -f cadence"
else
  echo
  if [[ "$TLS_MODE" == "external" ]]; then
    echo "Start the stack with:"
    echo "  docker compose -f docker-compose.prod.yml up -d --build"
  else
    echo "Start the stack with:"
    echo "  docker compose -f docker-compose.prod.yml --profile tls up -d --build"
  fi
fi
